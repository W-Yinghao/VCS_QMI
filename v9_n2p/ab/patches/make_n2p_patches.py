"""Generate the N2P DEV-only patch layer, applied AFTER v9/patches/{ncr,l2rm}_anchor_assisted.diff on a copy of the official clone.

Three changes, all inactive unless --n2p_dev_only <candidate dir> is given:
  1. split-path fix (both baselines): with the V9 observed mapping the anchor patch sets `_t2i_index = None`; the labeled /
     unlabeled split datasets then subscripted it (NCR health 1043807 and smoke 1043800 crashed there).  Keep it None.
     This line also runs without the flag; on the native path `_t2i_index` is never None, so it is unchanged there.
  2. candidate export: after every complete warm-up epoch and every complete main epoch, save the full candidate (NCR: both
     networks after both finished that epoch) to <candidate dir>/<phase>_<epoch>.pth.tar and append one ledger line with the
     native DEV validation the trainer computed anyway.  No extra validation, no extra data-loader pass, no RNG use.
  3. the native end-of-training TEST evalrank is skipped (run.py / main_L2RM.py).

    python make_n2p_patches.py --ncr <clone @60256ba> --l2rm <clone @a766c22> --anchor-patches <repo>/v9/patches --out <dir>
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import tempfile
from pathlib import Path

HEADER = ("N2P DEV-only layer (V9 N2P package 2026-10-20, phase B0): applied after v9/patches/{b}_anchor_assisted.diff.  Generated by "
          "v9_n2p/ab/patches/make_n2p_patches.py.  Inactive without --n2p_dev_only except the split-path None guard.\n")

SAVE_HELPER = '''

def n2p_save_candidate(opt, phase, epoch, state, native=None):
    """N2P: save one complete candidate checkpoint and append its ledger line (only with --n2p_dev_only)."""
    import json
    import time
    if not getattr(opt, "n2p_dev_only", ""):
        return
    os.makedirs(opt.n2p_dev_only, exist_ok=True)
    name = "{}_{:02d}.pth.tar".format(phase, epoch)
    state = dict(state, phase=phase, epoch=epoch, candidate_id="{}:{}".format(phase, epoch), opt=opt)
    torch.save(state, os.path.join(opt.n2p_dev_only, name))
    line = {"candidate_id": "{}:{}".format(phase, epoch), "phase": phase, "epoch": epoch, "file": name,
            "utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "native_dev": native}
    with open(os.path.join(opt.n2p_dev_only, "candidates.jsonl"), "a") as f:
        f.write(json.dumps(line) + "\\n")
    print("[N2P] candidate {} saved".format(line["candidate_id"]))
'''

ARG = '    parser.add_argument("--n2p_dev_only", default="", help="N2P: candidate directory; saves every epoch candidate and skips the native TEST evaluation")\n'


class Editor:
    def __init__(self, path: Path):
        self.path = path
        raw = path.read_bytes()
        self.nl = "\r\n" if b"\r\n" in raw else "\n"
        self.text = raw.decode("utf-8").replace("\r\n", "\n")

    def sub(self, old: str, new: str):
        n = self.text.count(old)
        assert n == 1, f"{self.path.name}: expected 1 match of {old[:70]!r}, found {n}"
        self.text = self.text.replace(old, new)

    def save(self):
        self.path.write_bytes(self.text.replace("\n", self.nl).encode("utf-8"))


def edit_ncr(root: Path):
    d = Editor(root / "NCR/data.py")
    d.sub("                self._t2i_index = [self._t2i_index[i] for i in split_idx]\n",
          "                self._t2i_index = None if self._t2i_index is None else [self._t2i_index[i] for i in split_idx]  # N2P: V9 mapping keeps it None\n")
    d.save()
    u = Editor(root / "NCR/utils.py")
    u.text = u.text.rstrip("\n") + "\n" + SAVE_HELPER
    u.save()
    r = Editor(root / "NCR/run.py")
    r.sub('    parser.add_argument("--anchor_mask_file"', ARG + '    parser.add_argument("--anchor_mask_file"')
    r.sub('    print("\\n*-------- Testing --------*")\n',
          '    if opt.n2p_dev_only:\n        print("\\n[N2P] native end-of-training TEST evaluation disabled (DEV-only adapter)")\n        return\n\n'
          '    print("\\n*-------- Testing --------*")\n')
    r.save()
    c = Editor(root / "NCR/co_train.py")
    c.sub("    adjust_learning_rate,\n)", "    adjust_learning_rate,\n    n2p_save_candidate,\n)")
    c.sub("            warmup(opt, noisy_trainloader, model_B, epoch)\n",
          "            warmup(opt, noisy_trainloader, model_B, epoch)\n"
          '            n2p_save_candidate(opt, "warmup", epoch, {"model_A": model_A.state_dict(), "model_B": model_B.state_dict()})\n')
    c.sub("        rsum = validate(opt, val_loader, [model_A, model_B])\n",
          "        rsum = validate(opt, val_loader, [model_A, model_B])\n"
          '        n2p_save_candidate(opt, "main", epoch, {"model_A": model_A.state_dict(), "model_B": model_B.state_dict()}, native={"rsum": rsum})\n')
    c.save()


def edit_l2rm(root: Path):
    d = Editor(root / "data.py")
    d.sub("            self._t2i_index = [self._t2i_index[i] for i in split_idx] #clean\n",
          "            self._t2i_index = None if self._t2i_index is None else [self._t2i_index[i] for i in split_idx]  # N2P: V9 mapping keeps it None\n")
    d.save()
    u = Editor(root / "utils.py")
    u.text = u.text.rstrip("\n") + "\nimport os\n" + SAVE_HELPER
    u.save()
    o = Editor(root / "opt.py")
    o.sub('    parser.add_argument("--anchor_mask_file"', ARG + '    parser.add_argument("--anchor_mask_file"')
    o.save()
    m = Editor(root / "main_L2RM.py")
    m.sub("    save_config\n)", "    save_config,\n    n2p_save_candidate,\n)")
    m.sub("            rsum = r1 + r5 + r10 + r1i + r5i + r10i\n",
          "            rsum = r1 + r5 + r10 + r1i + r5i + r10i\n"
          '            n2p_save_candidate(opt, "warmup", epoch, {"net": net.state_dict()}, native={"rsum": rsum})\n')
    m.sub("        rsum = r1 +  r5 + r10 + r1i + r5i + r10i\n",
          "        rsum = r1 +  r5 + r10 + r1i + r5i + r10i\n"
          '        n2p_save_candidate(opt, "main", epoch, {"net": net.state_dict(), "cost_function": cost_function.state_dict()}, native={"rsum": rsum})\n')
    m.sub('    # test\n    print("\\n*-------- Testing --------*")\n',
          '    # test\n    if opt.n2p_dev_only:\n        print("\\n[N2P] native end-of-training TEST evaluation disabled (DEV-only adapter)")\n        return\n'
          '    print("\\n*-------- Testing --------*")\n')
    m.save()


def make(clone: Path, anchor_patch: Path, edit, out: Path, name: str):
    with tempfile.TemporaryDirectory() as td:
        a, b = Path(td) / "a", Path(td) / "b"
        shutil.copytree(clone, a, ignore=shutil.ignore_patterns(".git", "__pycache__", "runs", "output", "noise_index", "*.png", "cc152k"))
        r = subprocess.run(["patch", "-p1", "-s", "-i", str(anchor_patch)], cwd=a, capture_output=True, text=True)
        assert r.returncode == 0, r.stdout + r.stderr
        shutil.copytree(a, b)
        edit(b)
        d = subprocess.run(["diff", "-ruN", "a", "b"], cwd=td, capture_output=True)
        assert d.returncode == 1, d.stderr
        (out / name).write_bytes(HEADER.format(b=name.split("_")[0]).encode() + d.stdout)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--ncr", required=True)
    ap.add_argument("--l2rm", required=True)
    ap.add_argument("--anchor-patches", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    make(Path(a.ncr), Path(a.anchor_patches) / "ncr_anchor_assisted.diff", edit_ncr, out, "ncr_n2p_devonly.diff")
    make(Path(a.l2rm), Path(a.anchor_patches) / "l2rm_anchor_assisted.diff", edit_l2rm, out, "l2rm_n2p_devonly.diff")


if __name__ == "__main__":
    main()
