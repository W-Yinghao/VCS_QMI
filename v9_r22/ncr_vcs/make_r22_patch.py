"""Generate the R22-B patch layer for NCR (ncr_r22_posterior.diff), applied AFTER v9/patches/ncr_anchor_assisted.diff and
v9_n2p/ab/patches/ncr_n2p_devonly.diff on a copy of the official clone (@60256ba).  Inactive without --r22_posterior.

  1. NCR/r22_posterior.py (new file, copied verbatim from v9_r22/ncr_vcs/r22_posterior.py).
  2. co_train.eval_train: with --r22_posterior the per-sample loss is computed by r22_posterior.eval_loss_and_diag, which makes the same calls
     as SGRAF.train(mode="eval_loss") and also returns the diagonal of the batch score matrix (the score of each observed pair).  After the
     official GMMs, r22_posterior.replace_probabilities returns the probabilities that NCR then uses everywhere it used the GMM clean
     probability: the labeled / unlabeled split (split_prob, p_threshold .5) and the label rectification weight of the labeled set.
     Not deployable -> that network's GMM probability (fallback).  The anchor patch then forces anchors to 1 / clean, as in NCR_A.
  3. run.py: --r22_posterior {"", vcs, bce}, --r22_roles_file, --r22_log.

    python make_r22_patch.py --ncr <clone @60256ba> --repo <worktree> --out <dir>
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = ("R22-B layer (round 22 alternative B, 2026-10-22): online VCS / matched-BCE clean posterior in place of the per-epoch GMM clean "
          "probability.  Applied after v9/patches/ncr_anchor_assisted.diff and v9_n2p/ab/patches/ncr_n2p_devonly.diff.  Generated by "
          "v9_r22/ncr_vcs/make_r22_patch.py.  Inactive without --r22_posterior.\n")


class Editor:
    def __init__(self, path: Path):
        self.path = path
        self.text = path.read_text()

    def sub(self, old: str, new: str):
        n = self.text.count(old)
        assert n == 1, f"{self.path.name}: expected 1 match of {old[:70]!r}, found {n}"
        self.text = self.text.replace(old, new)

    def save(self):
        self.path.write_text(self.text)


def edit(root: Path):
    shutil.copy(HERE / "r22_posterior.py", root / "NCR/r22_posterior.py")
    c = Editor(root / "NCR/co_train.py")
    c.sub("    n2p_save_candidate,\n)\n",
          "    n2p_save_candidate,\n)\n"
          "from r22_posterior import eval_loss_and_diag as r22_eval_loss_and_diag, replace_probabilities as r22_replace_probabilities\n")
    c.sub("    losses_B = torch.zeros(data_size)\n",
          "    losses_B = torch.zeros(data_size)\n"
          "    r22 = bool(getattr(opt, \"r22_posterior\", \"\"))  # R22-B: score of every observed pair, same eval pass\n"
          "    scores_A = torch.full((data_size,), float(\"nan\"), dtype=torch.float64)\n"
          "    scores_B = torch.full((data_size,), float(\"nan\"), dtype=torch.float64)\n")
    c.sub("            loss_A = model_A.train(images, captions, lengths, mode=\"eval_loss\")\n"
          "            loss_B = model_B.train(images, captions, lengths, mode=\"eval_loss\")\n",
          "            if r22:  # R22-B: the same eval_loss computation, plus the diagonal of the batch score matrix\n"
          "                loss_A, diag_A = r22_eval_loss_and_diag(model_A, images, captions, lengths)\n"
          "                loss_B, diag_B = r22_eval_loss_and_diag(model_B, images, captions, lengths)\n"
          "                r22_idx = torch.as_tensor([int(x) for x in ids])\n"
          "                scores_A[r22_idx] = diag_A.double().cpu()\n"
          "                scores_B[r22_idx] = diag_B.double().cpu()\n"
          "            else:\n"
          "                loss_A = model_A.train(images, captions, lengths, mode=\"eval_loss\")\n"
          "                loss_B = model_B.train(images, captions, lengths, mode=\"eval_loss\")\n")
    c.sub("    prob_B = prob_B[:, gmm_B.means_.argmin()]\n\n    return prob_A, prob_B, all_loss\n",
          "    prob_B = prob_B[:, gmm_B.means_.argmin()]\n\n"
          "    if r22:  # R22-B: the online posterior replaces the GMM clean probability (split + rectification); GMM is the fallback\n"
          "        if torch.isnan(scores_A).any() or torch.isnan(scores_B).any():\n"
          "            raise RuntimeError(\"R22-B: eval_train did not score every training pair\")\n"
          "        from data import collate_fn as r22_collate\n"
          "        prob_A, prob_B = r22_replace_probabilities(opt, epoch, data_loader.dataset, [model_A, model_B],\n"
          "                                                   [scores_A.numpy(), scores_B.numpy()], [prob_A, prob_B], r22_collate)\n"
          "    return prob_A, prob_B, all_loss\n")
    c.save()
    r = Editor(root / "NCR/run.py")
    r.sub('    parser.add_argument("--anchor_mask_file"',
          '    parser.add_argument("--r22_posterior", default="", choices=["", "vcs", "bce"], help="R22-B: online VCS / matched-BCE posterior replaces the GMM clean probability")\n'
          '    parser.add_argument("--r22_roles_file", default="", help="R22-B: int8 anchor role per caption (-1 = U)")\n'
          '    parser.add_argument("--r22_log", default="", help="R22-B: posterior ledger directory")\n'
          '    parser.add_argument("--anchor_mask_file"')
    r.sub("    opt = parser.parse_args()\n",
          "    opt = parser.parse_args()\n"
          "    if opt.r22_posterior and not (opt.r22_roles_file and opt.r22_log and opt.anchor_mask_file and opt.observed_index_file):\n"
          "        raise SystemExit(\"R22-B needs --r22_roles_file, --r22_log and the V9 observed index / anchor mask\")\n")
    r.save()


def make(clone: Path, repo: Path, out: Path):
    with tempfile.TemporaryDirectory() as td:
        a, b = Path(td) / "a", Path(td) / "b"
        shutil.copytree(clone, a, ignore=shutil.ignore_patterns(".git", "__pycache__", "runs", "output", "noise_index", "*.png", "cc152k"))
        for p in (repo / "v9/patches/ncr_anchor_assisted.diff", repo / "v9_n2p/ab/patches/ncr_n2p_devonly.diff"):
            r = subprocess.run(["patch", "-p1", "-s", "-i", str(p)], cwd=a, capture_output=True, text=True)
            assert r.returncode == 0, r.stdout + r.stderr
        shutil.copytree(a, b)
        edit(b)
        d = subprocess.run(["diff", "-ruN", "a", "b"], cwd=td, capture_output=True)
        assert d.returncode == 1, d.stderr
        (out / "ncr_r22_posterior.diff").write_bytes(HEADER.encode() + d.stdout)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--ncr", default="/projects/EEG-foundation-model/yinghao/code_v9/2021-NeurIPS-NCR")
    ap.add_argument("--repo", default=str(HERE.parents[1]))
    ap.add_argument("--out", default=str(HERE))
    a = ap.parse_args()
    make(Path(a.ncr), Path(a.repo), Path(a.out))


if __name__ == "__main__":
    main()
