"""V7X-30 B3: PN-VQA reimplemented from the EvalMuse paper (arXiv 2412.18150, §4.2 and §8.4-8.5; no code was released).
gen   (env v7x_llm): elements by the paper's Listing 1 (TIFA categories) and one yes / no question per element by Listing 2, with Qwen2.5-32B-Instruct in
      place of the paper's GPT-4 (reproduction adaptation; only the two examples each listing shows are used — the paper elides the rest).
      --elements parser: Listing 2 questions for the pinned V7 parser's elements instead (B3-P, a component comparison).
score (env v7x_llm): Qwen2-VL-7B-Instruct (the paper's best MLLM family) on 'This image is generated from {prompt}. Is the answer to {question} in
      this image {a}?' with a = the question's answer (P_T) and the other answer (P_F); P = softmax over the 'Yes' / 'No' next-token logits;
      S_e = (P_T + 1 - P_F) / 2; image score = mean S_e.  A prompt without a usable element gets 0 for every candidate (all tie), flagged.
    gen --prompts P --out G.jsonl [--elements own|parser] [--parser-cache C] [--shard k/n] [--limit N]
    score --gen G.jsonl [G2 ...] --inputs I --out S.jsonl [--shard k/n] [--limit N]"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import time
import zipfile
from pathlib import Path

MODELS = Path("/projects/EEG-foundation-model/yinghao/models"); LLM, MLLM = MODELS / "Qwen2.5-32B-Instruct", MODELS / "Qwen2-VL-7B-Instruct"
RANK = Path("/projects/EEG-foundation-model/yinghao/data/genai_rank")
SPLIT = """Given an aigc prompt, extract the elements that are important for generating images.
Classify each element into a type (object, human, animal, food, activity, attribute, counting, color, material, spatial, location, shape, other).
Examples are as follows, where Elements is in json format.

Prompt: A man posing for a selfie in a jacket and bow tie.
Elements:["man (human)", "selfie (activity)", "jacket (object)", "bow tie (object)", "posing (activity)"]

Prompt: A horse and several cows feed on hay.
Elements:["horse (animal)", "cows (animal)", "hay (object)", "feed on (activity)", "several (counting)"]

Prompt: {prompt}
Elements:"""
QUESTION = """Given a prompt for image generation and one of its related elements, generate one easy Yes/No question to verify whether the element is represented in the image generated by the prompt.

Description: A man posing for a selfie in a jacket and bow tie.
Element: man (human):
Q: Is this a man?
Choices: yes, no
A: yes

Description: Several Face mask and 0 nun
Element: 0 (Counting):
Q: Are there any nuns in the photo?
Choices: yes, no
A: no

Description: {caption}
Element: {element}:"""
VQA = "This image is generated from {prompt}. Is the answer to {question} in this image {a}?"


def read_jsonl(p):
    with open(p) as fh:
        return [json.loads(l) for l in fh if l.strip()]


def first_list(text):
    m = re.search(r"\[.*?\]", text, flags=re.S)
    try:
        v = json.loads(m.group(0)) if m else None
    except json.JSONDecodeError:
        v = None
    return [str(e).strip() for e in v if str(e).strip()] if isinstance(v, list) else None


def parse_qa(text):
    q = re.search(r"Q:\s*(.+)", text); a = re.search(r"A:\s*(yes|no)\b", text, flags=re.I)
    return (q.group(1).strip(), a.group(1).lower()) if q and a else None


def cmd_gen(a):
    sys.path.insert(0, str(Path(__file__).resolve().parent)); from x30_dsg import LocalLLM                     # the same local LLM wrapper as DSG
    k, n = (int(x) for x in a.shard.split("/")); prompts = [p for i, p in enumerate(read_jsonl(a.prompts)) if i % n == k][: a.limit or None]
    out = Path(a.out); done = {r["prompt_id"] for r in read_jsonl(out)} if out.exists() else set(); prompts = [p for p in prompts if p["prompt_id"] not in done]
    parser = {r["prompt"]: r for r in read_jsonl(a.parser_cache) if "prompt" in r} if a.elements == "parser" else {}
    llm = LocalLLM(LLM); t0 = time.time()
    with open(out, "a") as fh:
        for i, p in enumerate(prompts):
            if a.elements == "parser":
                pr = parser.get(p["prompt"]); els = [e["text"] for e in pr["elements"]] if pr and pr.get("status") == "ok" else []; raw_split = None
            else:
                raw_split = llm(SPLIT.format(prompt=p["prompt"])); els = first_list(raw_split) or []
            qas = []
            for e in els:
                raw = llm(QUESTION.format(caption=p["prompt"], element=e)); qa = parse_qa(raw)
                qas.append({"element": e, "raw": raw, "question": qa[0] if qa else None, "answer": qa[1] if qa else None, "parsed": qa is not None})
            fh.write(json.dumps({"prompt_id": p["prompt_id"], "prompt": p["prompt"], "elements_source": a.elements, "raw_split": raw_split, "qas": qas}) + "\n"); fh.flush()
            if i % 20 == 0:
                print(f"[pnvqa] gen {i + 1}/{len(prompts)} ({time.time() - t0:.0f}s, {llm.calls} LLM calls)", flush=True)
    return 0


class YesNo:
    """Qwen2-VL-7B-Instruct: P('Yes') = softmax over the 'Yes' / 'No' next-token logits after the chat generation prompt."""

    def __init__(self, path=MLLM):
        import torch
        from transformers import AutoProcessor, Qwen2VLForConditionalGeneration
        self.torch = torch; self.proc = AutoProcessor.from_pretrained(str(path)); self.proc.tokenizer.padding_side = "left"
        self.model = Qwen2VLForConditionalGeneration.from_pretrained(str(path), torch_dtype=torch.bfloat16, attn_implementation="sdpa", device_map="cuda").eval()
        ids = [self.proc.tokenizer.encode(w, add_special_tokens=False) for w in ("Yes", "No")]
        if any(len(i) != 1 for i in ids):
            raise SystemExit(f"'Yes' / 'No' are not single tokens: {ids}")
        self.yes, self.no = ids[0][0], ids[1][0]

    def p_yes(self, image, texts):
        from qwen_vl_utils import process_vision_info
        msgs = [[{"role": "user", "content": [{"type": "image", "image": image}, {"type": "text", "text": t}]}] for t in texts]
        chat = [self.proc.apply_chat_template(m, tokenize=False, add_generation_prompt=True) for m in msgs]; imgs, _ = process_vision_info(msgs)
        inp = self.proc(text=chat, images=imgs, padding=True, return_tensors="pt").to("cuda")
        with self.torch.no_grad():
            lg = self.model(**inp).logits[:, -1, :].float()
        two = self.torch.stack([lg[:, self.yes], lg[:, self.no]], 1)
        return self.torch.softmax(two, 1)[:, 0].cpu().tolist()


def cmd_score(a):
    gen = {}
    for g in a.gen:
        gen.update({r["prompt_id"]: r for r in read_jsonl(g)})
    k, n = (int(x) for x in a.shard.split("/")); cands = [c for i, c in enumerate(read_jsonl(a.inputs)) if i % n == k][: a.limit or None]
    out = Path(a.out); done = {r["image_id"] for r in read_jsonl(out)} if out.exists() else set(); cands = [c for c in cands if c["image_id"] not in done]
    local = Path(os.environ.get("V7X_LOCAL", "/tmp")) / "v7x_pnvqa_images"; zs = {}; m = YesNo(); t0 = time.time()
    with open(out, "a") as fh:
        for i, c in enumerate(cands):
            r = gen.get(c["prompt_id"])
            if r is None:
                raise SystemExit(f"no PN-VQA questions for prompt {c['prompt_id']}")
            qas = [q for q in r["qas"] if q["parsed"]]
            if not qas:
                rec = {"score": 0.0, "no_questions": True, "elements": []}
            else:
                g = c["image_id"].split("/")[0]; z = zs.get(g) or zs.setdefault(g, zipfile.ZipFile(RANK / f"{g}.zip")); p = local / c["image_id"]
                if not p.exists():
                    p.parent.mkdir(parents=True, exist_ok=True); p.write_bytes(z.read(c["image_id"]))
                texts = []
                for q in qas:
                    other = "no" if q["answer"] == "yes" else "yes"
                    texts += [VQA.format(prompt=r["prompt"], question=q["question"], a=q["answer"]), VQA.format(prompt=r["prompt"], question=q["question"], a=other)]
                pv = m.p_yes(str(p), texts); se = [(pv[2 * j] + 1 - pv[2 * j + 1]) / 2 for j in range(len(qas))]
                rec = {"score": float(sum(se) / len(se)), "no_questions": False, "elements": [{"element": q["element"], "P_T": pv[2 * j], "P_F": pv[2 * j + 1], "S_e": se[j]} for j, q in enumerate(qas)]}
            fh.write(json.dumps({"prompt_id": c["prompt_id"], "generator_id": c["generator_id"], "image_id": c["image_id"], "candidate_index": c["candidate_index"],
                                 "n_questions": len(qas), **rec}) + "\n"); fh.flush()
            if i % 200 == 0:
                print(f"[pnvqa] score {i + 1}/{len(cands)} ({time.time() - t0:.0f}s)", flush=True)
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(); sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("gen"); g.add_argument("--prompts", required=True); g.add_argument("--out", required=True); g.add_argument("--elements", choices=["own", "parser"], default="own")
    g.add_argument("--parser-cache", default="/projects/EEG-foundation-model/yinghao/outputs_v7/parser/genai_prompts_cache_v3.jsonl"); g.add_argument("--shard", default="0/1"); g.add_argument("--limit", type=int, default=0)
    s = sub.add_parser("score"); s.add_argument("--gen", nargs="+", required=True); s.add_argument("--inputs", required=True); s.add_argument("--out", required=True)
    s.add_argument("--shard", default="0/1"); s.add_argument("--limit", type=int, default=0)
    a = ap.parse_args(argv)
    return {"gen": cmd_gen, "score": cmd_score}[a.cmd](a)


if __name__ == "__main__":
    sys.exit(main())
