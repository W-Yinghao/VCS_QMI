"""V9-G2 report writer: every number comes from reports/V9/V9_G2_results/g2_results.json (written by scripts/v9/reg_g2.py aggregate); the
[解释] section is rendered mechanically from the frozen wording rules (reports/V9/V9_G2_PROTOCOL_FROZEN_20261015.yaml wording_fixed) — no number is typed.
    python scripts/v9/reg_g2_report.py [--results reports/V9/V9_G2_results/g2_results.json] [--out reports/V9/V9_G2_REPORT_<date>.md] [--jobs "..."]"""
from __future__ import annotations

import argparse
import datetime as dt
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
METHODS = ("vcs", "logistic", "infonce", "comir", "kernel"); FR = ("0.25", "1"); EP = ("0", "0.2")
NAME = {"vcs": "VCS", "logistic": "logistic (BCE)", "infonce": "InfoNCE", "comir": "CoMIR", "kernel": "kernel (seed 901)", "mi": "MI", "nmi": "NMI"}


def pct(t, sd=True):
    if not t or t.get("mean") is None:
        return "—"
    return f"{100 * t['mean']:.1f}" + (f" ± {100 * t['sd']:.1f}" if sd and t.get("sd") is not None else "")


def iv(t, key="ci95"):
    v = t.get(key); return f"[{100 * v[0]:+.1f}, {100 * v[1]:+.1f}]" if v else "—"


def excl(v):
    return v is not None and (v[0] > 0 or v[1] < 0)


def wording(c):
    """Frozen wording: interval containing 0 -> no detectable difference; otherwise VCS registers more / fewer DEV scenes."""
    both = excl(c.get("ci95")) and excl(c.get("unit_boot95"))
    if not both:
        return "no detectable difference"
    return f"VCS registers {'more' if c['mean'] > 0 else 'fewer'} DEV scenes ({100 * c['mean']:+.1f} pp)"


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--results", type=Path, default=REPO / "reports/V9/V9_G2_results/g2_results.json")
    ap.add_argument("--out", type=Path, default=None); ap.add_argument("--jobs", default=""); ap.add_argument("--commit", default=""); a = ap.parse_args()
    r = json.load(open(a.results)); date = dt.date.today().strftime("%Y%m%d"); out = a.out or REPO / f"reports/V9/V9_G2_REPORT_{date}.md"
    C, K, P, I = r["cells"], r["contrasts"], r["primary"], r["interaction"]
    L = [f"# V9-G2 report — EPFL RGB–NIR: training-sample fraction × training-correspondence mismatch ({dt.date.today().isoformat()})", "",
         f"Protocol `V9_G2_PROTOCOL_FROZEN_20261015.yaml` (frozen 2026-10-15T18:37:18Z before any formal run).  Jobs: {a.jobs or 'see reports/V9/V9_JOB_IDS.json'}.  "
         f"Every number below is generated by `scripts/v9/reg_g2_report.py` from `V9_G2_results/g2_results.json`, which `scripts/v9/reg_g2.py aggregate` writes from the "
         f"per-unit result JSON under `/projects/EEG-foundation-model/yinghao/outputs_v9/reg_epfl/units/` (REG-P3's register_one) and REG-P3's reused MI / NMI results "
         f"(hash check: perturbations {r['mi_nmi_reuse']['perturbations_sha256']}, manifest {r['mi_nmi_reuse']['manifest_sha256']}).  Missing units: {r['missing'] or 'none'}.  "
         f"Package §09.3 format: [已知证据] / [本轮结果] / [解释] / [未验证假设].", "",
         "## [已知证据] (r6 REG-P3; package docs/06 §2)",
         "- r6 REG-P3 (EPFL, seeds 0–2, full FIT, clean correspondences) established the data, roles (DEV 72 scene units / 74 windows, CAL 9 / 10, FIT 330 / 336), the",
         "  rigid perturbations (10 per CAL / DEV window), the thresholds (err_full < 42 / < 9 = 10.5 / 2.25 native px; the dataset's own alignment is accurate to ≈ 2 px) and the",
         "  unit-pooled selection / evaluation.  DEV was read by REG-P3, so every DEV number here is development validation, not a confirmation.",
         "- V9-G1 ran the same two axes on BF/SHG (its report stands on its own; G1 and G2 are two datasets reported side by side, not pooled).",
         "- Nothing in this report assumes that a bounded objective is robust to noisy supervision (docs/06 §1).", "",
         "## [本轮结果]", "",
         f"Ceiling readout (pre-registered): every method's CAL unit success < 10.5 px ≥ 0.95 → **{r['ceiling_readout']['all_cal_success42_ge_0.95']}** "
         f"(minimum CAL success {100 * r['ceiling_readout']['min_cal_success42']:.1f} %)" + (" → the < 2.25 px success is the discriminating readout (truth caveat)." if r['ceiling_readout']['all_cal_success42_ge_0.95'] else " → the < 10.5 px success stays primary."), "",
         "### DEV success by cell (unit-macro over 72 DEV scenes; mean ± sd over seeds 901–903; kernel one seed)", "",
         "| method | FIT fraction | ε | n FIT units | success < 10.5 px (%) | success < 2.25 px (%) | median corner error (err_full px) | failures (energy) | chosen ckpt | realised ε |", "|---|---|---|---|---|---|---|---|---|---|"]
    for m in METHODS:
        for f in FR:
            for e in EP:
                c = C.get(f"{m}|frac{f}|eps{e}")
                if not c:
                    L.append(f"| {NAME[m]} | {f} | {e} | — | missing | | | | | |"); continue
                L.append(f"| {NAME[m]} | {f} | {e} | {c['n_fit_units']} | {pct(c['success42'])} | {pct(c['success9'])} | {c['dev_median_err']['mean']:.2f} | {sum(c['failures42'])} ({sum(c['failures42_energy'])}) | "
                         f"{', '.join(str(x) for x in c.get('chosen_ckpt', [])) or '—'} | {', '.join(f'{x:.3f}' for x in c.get('realised_mismatch', []) if x is not None) or '—'} |")
    for m in ("mi", "nmi"):
        c = C.get(m)
        if c:
            L.append(f"| {NAME[m]} (reused, no training) | — | — | — | {pct(c['success42'])} | {pct(c['success9'])} | {c['dev_median_err']['mean']:.2f} | {sum(c['failures42'])} ({sum(c['failures42_energy'])}) | — | — |")
    L += ["", "### Primary family (VCS − MI, VCS − CoMIR at ε 0.2, both fractions; success < 10.5 px; Holm over 4)", "",
          "| contrast | Δ (pp) | seed t 95 % | unit bootstrap 95 % | boot p | Holm p | detected | seeds paired |", "|---|---|---|---|---|---|---|---|"]
    for k, c in P.items():
        L.append(f"| {k} | {100 * c['mean']:+.1f} | {iv(c)} | {iv(c, 'unit_boot95')} | {c['boot_p']:.4f} | {c['p_holm']:.4f} | **{c['detected']}** | {len(c['pairs'])} |")
    L += ["", "### Interaction: seed-paired change of success < 10.5 px from ε 0 to 0.2 (pp)", "", "| method | fraction 0.25 | fraction 1 |", "|---|---|---|"]
    for m in METHODS:
        row = [I.get(f"{m}|frac{f}|delta_0_to_0.2@42") for f in FR]
        L.append(f"| {NAME[m]} | " + " | ".join((f"{100 * t['mean']:+.1f} {iv(t)}" if t else "—") for t in row) + " |")
    L += ["", "### All VCS − X contrasts (pp; seed t 95 % / unit bootstrap 95 %)", "", "| contrast | Δ | seed t | unit bootstrap | boot p |", "|---|---|---|---|---|"]
    L += [f"| {k} | {100 * c['mean']:+.1f} | {iv(c)} | {iv(c, 'unit_boot95')} | {c['boot_p']:.4f} |" for k, c in K.items()]
    L += ["", "## [解释]", "", "Rendered from the frozen wording rules; no claim beyond them.", ""]
    for k, c in P.items():
        L.append(f"- {k}: {wording(c)} (Holm p {c['p_holm']:.4f}; {'complete' if c['complete'] else 'INCOMPLETE — fewer than 3 seed pairs'}).")
    for f in FR:
        cls = [K.get(f"vcs_minus_{o}|frac{f}|eps0.2@42") for o in ("logistic", "infonce")]
        if all(cls):
            same = all(not (excl(c.get("ci95")) and excl(c.get("unit_boot95"))) for c in cls)
            L.append(f"- Fraction {f}, ε 0.2: VCS − logistic {100 * cls[0]['mean']:+.1f} {iv(cls[0])}, VCS − InfoNCE {100 * cls[1]['mean']:+.1f} {iv(cls[1])} → "
                     + ("VCS ≈ logistic ≈ InfoNCE: whatever the VCS − MI / VCS − CoMIR readings show is a learned relational-energy class effect, not a VCS-only effect."
                        if same else "the critic objectives differ at this cell; the VCS − X readings are reported as such (no class-effect wording)."))
    L += ["- A stronger CoMIR / MI / NMI cell, where it occurs above, is reported as is; no baseline was weakened (recipes frozen).",
          "- The interaction rows are descriptive (intervals shown); no test of the differences of changes.",
          "", "## [未验证假设]", "",
          "- DEV results are development validation (DEV seen by r6 REG-P3); no sealed EPFL split exists, so no confirmation claim is made.",
          "- Success < 2.25 native px is read with the 2-px truth caveat (the dataset's own RGB–NIR alignment).",
          "- Transfer between BF/SHG (G1) and RGB–NIR (G2) is not tested: the two reports stand side by side.",
          "- The mismatch model is the conditional displaced-position Q of the frozen protocol (same crop, ≥ 2 patch radii); other noise models (unconditional, outlier scenes, occlusion) are untested.",
          "- The kernel row is one seed (descriptive); MI / NMI are deterministic reused rows (no seed variance).", ""]
    out.write_text("\n".join(L)); print(f"-> {out}"); return 0


if __name__ == "__main__":
    raise SystemExit(main())
