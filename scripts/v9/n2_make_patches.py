def make(name: str, clone: Path, files: list[str], out: Path, fn):
    with tempfile.TemporaryDirectory() as td:
        a, b = Path(td, "a"), Path(td, "b")
        for d in (a, b):
            for f in files:
                (d / f).parent.mkdir(parents=True, exist_ok=True); shutil.copy(clone / f, d / f)
        fn(b)
        diff = subprocess.run(["diff", "-ruN", "a", "b"], cwd=td, capture_output=True).stdout.decode("utf-8")   # bytes: keep the files' CRLF intact
    diff = re.sub(r"^--- a/(\S+)[^\r\n]*$", r"--- a/\1", diff, flags=re.M); diff = re.sub(r"^\+\+\+ b/(\S+)[^\r\n]*$", r"+++ b/\1", diff, flags=re.M)
    p = out / f"{name}_anchor_assisted.diff"; p.write_bytes((HEADERS[name] + diff).encode("utf-8"))
    chk = subprocess.run(["git", "apply", "--check", str(p.resolve())], cwd=clone, capture_output=True, text=True)
    print(f"{name}: {p} ({diff.count(chr(10))} lines) git apply --check -> {'OK' if chk.returncode == 0 else 'FAIL: ' + chk.stderr}")
    return chk.returncode == 0


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--ncr", required=True); ap.add_argument("--l2rm", required=True); ap.add_argument("--out", default="v9/patches"); a = ap.parse_args()
    out = Path(a.out); out.mkdir(parents=True, exist_ok=True)
    ok = make("ncr", Path(a.ncr), ["NCR/run.py", "NCR/data.py", "NCR/co_train.py"], out, patch_ncr)
    ok &= make("l2rm", Path(a.l2rm), ["opt.py", "data.py", "main_L2RM.py"], out, patch_l2rm)
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
