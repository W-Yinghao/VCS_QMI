"""Generate the NCR+A / L2RM+A patches from explicit string edits on pristine copies of the official code (reproducible; the diffs are the
artefacts the launcher applies).  Every edit asserts exactly one match.  Line endings of the official files (L2RM is CRLF) are preserved.

    python scripts/v9/n2_make_patches.py --ncr <clone @60256ba> --l2rm <clone @a766c22> --out v9/patches

Changes (all guarded: with `--observed_index_file` / `--anchor_mask_file` empty, every patched line is skipped and the native path runs —
the degradation check `scripts/v9/n2_degradation.py` proves it):
  NCR  run.py: two arguments; data.py: PrecompDataset / get_loader accept and forward them, the observed index replaces the noise index, clean labels
       become -1 (not exposed); co_train.py: the three train loaders receive them; after the GMM split anchors are labeled with prob 1 (both nets).
  L2RM opt.py: two arguments; data.py: PrecompDataset / PrecompDataset_split / get_loader / get_loader_split likewise; main_L2RM.py: the three loaders
       receive them; after the BMM split anchors are always in the correct set; the clean-label statistics are skipped when labels are -1.
"""
from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

HEADERS = {
    "ncr": """V9-N2 "NCR+A" (package docs/05 §1, §6): the official NCR route with the SAME trusted anchor budget.  Generated by scripts/v9/n2_make_patches.py
against https://github.com/XLearning-SCU/2021-NeurIPS-NCR @ 60256ba.  With --observed_index_file / --anchor_mask_file empty the native code path runs
unchanged (degradation check).  Changes: run.py two arguments; data.py PrecompDataset + get_loader take the V9 observed mapping (A clean, donors from
U) instead of the noise index and set the clean labels to -1 (never exposed to the trainer); co_train.py forwards them and, after the GMM split,
labels every anchor pair with clean probability 1 for both networks (the anchor-supervised term with weight 1).  Co-training, soft margin, the
two-model averaged evaluation and the dev selection stay official.
""",
    "l2rm": """V9-N2 "L2RM+A" (package docs/05 §1, §6): the official L2RM route (OT / partial-OT rematching kept in full) with the SAME trusted anchor budget.
Generated by scripts/v9/n2_make_patches.py against https://github.com/hhc1997/L2RM @ a766c22 (CRLF files preserved).  With --observed_index_file /
--anchor_mask_file empty the native code path runs unchanged (degradation check).  Changes: opt.py two arguments; data.py PrecompDataset,
PrecompDataset_split, get_loader, get_loader_split take the V9 observed mapping and set clean labels to -1; main_L2RM.py forwards them, forces anchor
pairs into the correct set after the BMM split, and skips the clean-label statistics when labels are -1.
""",
}


class Editor:
    def __init__(self, path: Path):
        self.path = path; raw = path.read_bytes(); self.nl = "\r\n" if b"\r\n" in raw else "\n"; self.text = raw.decode("utf-8").replace("\r\n", "\n")

    def sub(self, old: str, new: str, count: int = 1):
        n = self.text.count(old)
        assert n == count, f"{self.path.name}: expected {count} match(es) of {old[:60]!r}, found {n}"
        self.text = self.text.replace(old, new)

    def resub(self, pattern: str, repl, count: int):
        self.text, n = re.subn(pattern, repl, self.text, flags=re.M)
        assert n == count, f"{self.path.name}: expected {count} regex match(es) of {pattern!r}, found {n}"

    def save(self):
        self.path.write_bytes(self.text.replace("\n", self.nl).encode("utf-8"))


ARGS = ('    parser.add_argument("--observed_index_file", default="", help="V9-N2: observed caption->image mapping (npy); empty = native noise index")\n'
        '    parser.add_argument("--anchor_mask_file", default="", help="V9-N2: boolean anchor mask per caption (npy); empty = no anchor term")\n')
LABELS_OLD = '            self._labels = np.ones((self.length), dtype="int")\n            self._labels[self._t2i_index != self.t2i_index] = 0\n'
LABELS_NEW = ('            if self._t2i_index is None:\n                self._labels = -np.ones((self.length), dtype="int")\n            else:\n'
              '                self._labels = np.ones((self.length), dtype="int")\n                self._labels[self._t2i_index != self.t2i_index] = 0\n')


def observed_branch(indent: str) -> str:
    i = indent
    return (f"{i}if observed_index_file:\n{i}    # V9-N2: trust-assisted observed mapping (caption -> observed image); A pairs clean, donors from U only.\n"
            f"{i}    print(\"=> load V9 observed index from {{}}\".format(observed_index_file))\n{i}    self.t2i_index = np.load(observed_index_file)\n"
            f"{i}    assert len(self.t2i_index) == self.length\n{i}    self.anchor_mask = np.load(anchor_mask_file).astype(bool) if anchor_mask_file else None\n"
            f"{i}    # the original mapping is not exposed to the trainer in V9: clean labels unknown (-1)\n{i}    self._t2i_index = None\n{i}elif noise_ratio:\n")


def patch_ncr(root: Path):
    e = Editor(root / "NCR/run.py"); e.sub('    parser.add_argument("--noise_ratio", default=0.2, type=float, help="Noisy ratio")\n', '    parser.add_argument("--noise_ratio", default=0.2, type=float, help="Noisy ratio")\n' + ARGS); e.save()
    e = Editor(root / "NCR/data.py")
    e.sub('        noise_file="",\n        mode="",', '        noise_file="",\n        observed_index_file="",\n        anchor_mask_file="",\n        mode="",')
    e.sub("            self._t2i_index = copy.deepcopy(self.t2i_index)\n            if noise_ratio:\n", "            self._t2i_index = copy.deepcopy(self.t2i_index)\n" + observed_branch("            "))
    e.sub(LABELS_OLD, LABELS_NEW)
    e.sub("    noise_file=\"\",\n    pred=[],\n    prob=[],\n):", "    noise_file=\"\",\n    pred=[],\n    prob=[],\n    observed_index_file=\"\",\n    anchor_mask_file=\"\",\n):")
    e.sub('        dset = PrecompDataset(captions, images, "train", noise_ratio, noise_file)\n', '        dset = PrecompDataset(captions, images, "train", noise_ratio, noise_file, observed_index_file=observed_index_file, anchor_mask_file=anchor_mask_file)\n')
    e.sub('            mode="labeled",\n            pred=pred,\n            probability=prob,\n        )', '            mode="labeled",\n            pred=pred,\n            probability=prob,\n            observed_index_file=observed_index_file,\n            anchor_mask_file=anchor_mask_file,\n        )')
    e.sub('            mode="unlabeled",\n            pred=pred,\n            probability=prob,\n        )', '            mode="unlabeled",\n            pred=pred,\n            probability=prob,\n            observed_index_file=observed_index_file,\n            anchor_mask_file=anchor_mask_file,\n        )')
    e.save()
    e = Editor(root / "NCR/co_train.py")
    e.resub(r"^(\s+)opt\.noise_file,\n", lambda m: f"{m.group(1)}opt.noise_file,\n{m.group(1)}observed_index_file=opt.observed_index_file,\n{m.group(1)}anchor_mask_file=opt.anchor_mask_file,\n", 3)
    e.sub("        pred_A = split_prob(prob_A, opt.p_threshold)\n        pred_B = split_prob(prob_B, opt.p_threshold)\n",
          "        pred_A = split_prob(prob_A, opt.p_threshold)\n        pred_B = split_prob(prob_B, opt.p_threshold)\n"
          "        # V9-N2 anchor-supervised term: trusted anchor pairs are always labeled with clean probability 1 (weight 1), both networks.\n"
          "        if getattr(opt, \"anchor_mask_file\", \"\"):\n            anchor = np.load(opt.anchor_mask_file).astype(bool)\n"
          "            prob_A[anchor] = 1.0\n            prob_B[anchor] = 1.0\n            pred_A[anchor] = True\n            pred_B[anchor] = True\n")
    e.save()


